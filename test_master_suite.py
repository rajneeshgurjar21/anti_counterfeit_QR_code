"""
Comprehensive 12-Scenario Anti-Counterfeit QR Authentication Test Suite
=======================================================================
Implements the exact testing requirements from Section 6 of the Master Prompt:
1. Original QR generated by the application (digital master).
2. Genuine print photographed straight-on under good lighting.
3. Genuine print photographed at a moderate angle (perspective distortion).
4. Genuine print photographed under different lighting conditions (illumination gradient/shadows).
5. Genuine print captured using different mobile cameras (sensor noise, sharpness variations).
6. A slightly blurred or low-resolution photograph.
7. A cropped or partially obstructed QR code (testing error resilience / UNREADABLE).
8. A photocopy or reprint of an original QR (2nd-gen reprint attack).
9. An unknown or modified QR code (serial not in brand registry).
10. A genuine identifier with an altered or substituted security graphic (wrong CDP / seed mismatch).
11. An unavailable reference or revoked/blacklisted product.
12. Repeated scans of the same identifier (multi-scan clone alert).
"""

import cv2
import numpy as np
from PIL import Image
import json
import os
import sys

from cdp_engine import create_anti_counterfeit_qr
from cdp_verifier import verify_anti_counterfeit_qr
import product_db

def test_master_scenarios():
    print("=" * 78)
    print("STARTING 12-SCENARIO ANTI-COUNTERFEIT QR TEST SUITE")
    print("=" * 78)
    
    # Pre-register test product
    TEST_SERIAL = "PROD-TEST-MASTER-01"
    TEST_PAYLOAD = f"https://brand-auth.com/verify?id={TEST_SERIAL}&batch=B01"
    product_db.register_product(
        serial_no=TEST_SERIAL,
        product_name="MasterShield Vaccine 10ml",
        brand_name="Aura Pharma Global",
        batch_no="B01",
        mfg_date="2026-03-01",
        exp_date="2029-03-01",
        mrp="Rs. 1,250.00"
    )
    
    # Generate master QR
    qr_master_pil, cdp_master_pil = create_anti_counterfeit_qr(
        payload=TEST_PAYLOAD,
        serial_no=TEST_SERIAL,
        box_size=12,
        cdp_ratio=0.32
    )
    qr_master_cv = cv2.cvtColor(np.array(qr_master_pil), cv2.COLOR_RGB2BGR)
    h, w = qr_master_cv.shape[:2]
    
    results = []
    
    def log_result(scen_num, scen_name, expected, actual, score, verdict, metrics, passed):
        results.append({
            "scenario_num": scen_num,
            "name": scen_name,
            "expected": expected,
            "actual": actual,
            "score": score,
            "verdict": verdict,
            "metrics": metrics,
            "passed": passed
        })
        status_str = "PASS [OK]" if passed else "FAIL [XX]"
        print(f"[{status_str}] Scenario {str(scen_num):>2}: {scen_name}")
        print(f"       Expected: {expected:<14} | Got: {actual:<14} | Score: {score:5.1f}% | Verdict: {verdict}")
        if metrics:
            ncc = metrics.get('peak_ncc', 0)
            lap = metrics.get('laplacian_edge_variance', 0)
            hf = metrics.get('fft_high_freq_ratio', 0)
            print(f"       Metrics -> NCC: {ncc:.3f} | Laplacian: {lap:7.1f} | FFT-HF: {hf:.6f}")
        print("-" * 78)

    # ──────────────────────────────────────────────────────────────────────────
    # Scenario 1: Original QR generated by application (Digital Master 600 DPI)
    # ──────────────────────────────────────────────────────────────────────────
    res1 = verify_anti_counterfeit_qr(qr_master_cv, TEST_SERIAL)
    passed1 = res1.get("is_genuine") and res1.get("authenticity_score") >= 90.0
    log_result(
        1, "Original Master QR (Digital / 600 DPI)",
        "GENUINE", res1.get("status"), res1.get("authenticity_score", 0),
        res1.get("verdict"), res1.get("metrics"), passed1
    )

    # ──────────────────────────────────────────────────────────────────────────
    # Scenario 2: Genuine print photographed straight-on under good lighting
    # ──────────────────────────────────────────────────────────────────────────
    # Typical phone: 5x5 blur, sigma 1.8, JPEG 75
    b2 = cv2.GaussianBlur(qr_master_cv, (5, 5), 1.8)
    _, buf2 = cv2.imencode('.jpg', b2, [cv2.IMWRITE_JPEG_QUALITY, 75])
    img2 = cv2.imdecode(buf2, cv2.IMREAD_COLOR)
    res2 = verify_anti_counterfeit_qr(img2, TEST_SERIAL)
    passed2 = res2.get("is_genuine") and res2.get("authenticity_score") >= 65.0
    log_result(
        2, "Genuine Print - Phone Photo (Straight-on)",
        "GENUINE", res2.get("status"), res2.get("authenticity_score", 0),
        res2.get("verdict"), res2.get("metrics"), passed2
    )

    # ──────────────────────────────────────────────────────────────────────────
    # Scenario 3: Genuine print photographed at a moderate angle (Perspective warp)
    # ──────────────────────────────────────────────────────────────────────────
    # Simulate ~15 degree tilt by moving corners inward
    pts1 = np.float32([[0, 0], [w, 0], [w, h], [0, h]])
    pts2 = np.float32([[25, 20], [w - 35, 10], [w - 15, h - 25], [35, h - 15]])
    M3 = cv2.getPerspectiveTransform(pts1, pts2)
    warped3 = cv2.warpPerspective(qr_master_cv, M3, (w + 40, h + 40), borderValue=(255, 255, 255))
    b3 = cv2.GaussianBlur(warped3, (3, 3), 1.2)
    _, buf3 = cv2.imencode('.jpg', b3, [cv2.IMWRITE_JPEG_QUALITY, 80])
    img3 = cv2.imdecode(buf3, cv2.IMREAD_COLOR)
    res3 = verify_anti_counterfeit_qr(img3, TEST_SERIAL)
    passed3 = res3.get("is_genuine") and res3.get("authenticity_score") >= 65.0
    log_result(
        3, "Genuine Print - Moderate Angle / Perspective Tilt",
        "GENUINE", res3.get("status"), res3.get("authenticity_score", 0),
        res3.get("verdict"), res3.get("metrics"), passed3
    )

    # ──────────────────────────────────────────────────────────────────────────
    # Scenario 4: Genuine print photographed under different lighting (Shadow gradient)
    # ──────────────────────────────────────────────────────────────────────────
    y, x = np.mgrid[0:h, 0:w]
    grad4 = 0.70 + 0.30 * (x + y) / (w + h)  # 70% to 100% illumination ramp
    lit4 = np.clip(qr_master_cv.astype(np.float32) * grad4[:, :, np.newaxis], 0, 255).astype(np.uint8)
    b4 = cv2.GaussianBlur(lit4, (5, 5), 1.5)
    _, buf4 = cv2.imencode('.jpg', b4, [cv2.IMWRITE_JPEG_QUALITY, 78])
    img4 = cv2.imdecode(buf4, cv2.IMREAD_COLOR)
    res4 = verify_anti_counterfeit_qr(img4, TEST_SERIAL)
    passed4 = res4.get("is_genuine") and res4.get("authenticity_score") >= 65.0
    log_result(
        4, "Genuine Print - Non-uniform Lighting / Shadow",
        "GENUINE", res4.get("status"), res4.get("authenticity_score", 0),
        res4.get("verdict"), res4.get("metrics"), passed4
    )

    # ──────────────────────────────────────────────────────────────────────────
    # Scenario 5: Genuine print captured with different mobile camera (Noisy sensor)
    # ──────────────────────────────────────────────────────────────────────────
    noise5 = np.random.normal(0, 3.5, qr_master_cv.shape).astype(np.float32)
    noisy5 = np.clip(qr_master_cv.astype(np.float32) + noise5, 0, 255).astype(np.uint8)
    b5 = cv2.GaussianBlur(noisy5, (3, 3), 1.3)
    _, buf5 = cv2.imencode('.jpg', b5, [cv2.IMWRITE_JPEG_QUALITY, 80])
    img5 = cv2.imdecode(buf5, cv2.IMREAD_COLOR)
    res5 = verify_anti_counterfeit_qr(img5, TEST_SERIAL)
    passed5 = res5.get("is_genuine") and res5.get("authenticity_score") >= 65.0
    log_result(
        5, "Genuine Print - Budget Camera Sensor Noise",
        "GENUINE", res5.get("status"), res5.get("authenticity_score", 0),
        res5.get("verdict"), res5.get("metrics"), passed5
    )

    # ──────────────────────────────────────────────────────────────────────────
    # Scenario 6: Slightly blurred or low-resolution capture
    # ──────────────────────────────────────────────────────────────────────────
    b6 = cv2.GaussianBlur(qr_master_cv, (7, 7), 2.2)
    _, buf6 = cv2.imencode('.jpg', b6, [cv2.IMWRITE_JPEG_QUALITY, 68])
    img6 = cv2.imdecode(buf6, cv2.IMREAD_COLOR)
    res6 = verify_anti_counterfeit_qr(img6, TEST_SERIAL)
    # Should be SUSPICIOUS or mild Genuine / prompt recapture without claiming fake blindly
    passed6 = res6.get("status") in ["SUSPICIOUS", "GENUINE", "RECAPTURE_REQUIRED"]
    log_result(
        6, "Slightly Blurred / Low-Res Capture",
        "SUSPICIOUS/GENUINE", res6.get("status"), res6.get("authenticity_score", 0),
        res6.get("verdict"), res6.get("metrics"), passed6
    )

    # ──────────────────────────────────────────────────────────────────────────
    # Scenario 7: Cropped or partially obstructed QR code
    # ──────────────────────────────────────────────────────────────────────────
    # Crop out 40% of the image (QR finder patterns destroyed)
    img7 = qr_master_cv[int(h * 0.35):, int(w * 0.35):].copy()
    res7 = verify_anti_counterfeit_qr(img7, TEST_SERIAL)
    passed7 = res7.get("status") in ["UNREADABLE", "RECAPTURE_REQUIRED"]
    log_result(
        7, "Cropped / Obstructed QR Code",
        "UNREADABLE", res7.get("status"), res7.get("authenticity_score", 0),
        res7.get("verdict"), res7.get("metrics"), passed7
    )

    # ──────────────────────────────────────────────────────────────────────────
    # Scenario 8a: 2nd-Gen Reprint Attack (Rescan MTF Loss / Acutance Collapse)
    # ──────────────────────────────────────────────────────────────────────────
    p1 = cv2.GaussianBlur(qr_master_cv, (5, 5), 2.0)
    low = cv2.resize(p1, (int(w * 0.75), int(h * 0.75)), interpolation=cv2.INTER_LINEAR)
    reprinted = cv2.resize(low, (w, h), interpolation=cv2.INTER_LINEAR)
    p2 = cv2.GaussianBlur(reprinted, (7, 7), 2.5)
    _, buf8a = cv2.imencode('.jpg', p2, [cv2.IMWRITE_JPEG_QUALITY, 60])
    img8a = cv2.imdecode(buf8a, cv2.IMREAD_COLOR)
    res8a = verify_anti_counterfeit_qr(img8a, TEST_SERIAL)
    passed8a = (not res8a.get("is_genuine")) and res8a.get("authenticity_score", 0) <= 35.0
    log_result(
        "8a", "2nd-Gen Reprint Attack (Low Acutance / Blur)",
        "COUNTERFEIT", res8a.get("status"), res8a.get("authenticity_score", 0),
        res8a.get("verdict"), res8a.get("metrics"), passed8a
    )

    # ──────────────────────────────────────────────────────────────────────────
    # Scenario 8b: Office Photocopier Attack (Unsharp Masking + Toner Clumping)
    # ──────────────────────────────────────────────────────────────────────────
    # Photocopier optical scan + copier DSP contrast sharpening + toner saturation
    gray_m = cv2.cvtColor(qr_master_cv, cv2.COLOR_BGR2GRAY)
    scan_m = cv2.GaussianBlur(gray_m, (3, 3), 0.8)
    gauss_m = cv2.GaussianBlur(scan_m, (5, 5), 1.5)
    sharp_m = cv2.addWeighted(scan_m, 2.0, gauss_m, -1.0, 0)
    stretch_m = np.clip(np.power(sharp_m.astype(np.float32) / 255.0, 1.35) * 255.0, 0, 255).astype(np.uint8)
    kern_m = cv2.getStructuringElement(cv2.MORPH_ELLIPSE, (3, 3))
    dilated_m = cv2.dilate(255 - stretch_m, kern_m, iterations=1)
    reprint_m = cv2.GaussianBlur(255 - dilated_m, (3, 3), 0.7)
    phone_m = cv2.GaussianBlur(reprint_m, (3, 3), 0.8)
    img8b = cv2.cvtColor(phone_m, cv2.COLOR_GRAY2BGR)
    res8b = verify_anti_counterfeit_qr(img8b, TEST_SERIAL)
    passed8b = (not res8b.get("is_genuine")) and res8b.get("authenticity_score", 0) <= 25.0
    log_result(
        "8b", "Office Photocopier Attack (Toner Bleed / Clumping)",
        "COUNTERFEIT", res8b.get("status"), res8b.get("authenticity_score", 0),
        res8b.get("verdict"), res8b.get("metrics"), passed8b
    )

    # ──────────────────────────────────────────────────────────────────────────
    # Scenario 9: Unknown or modified QR code (Not registered in DB)
    # ──────────────────────────────────────────────────────────────────────────
    UNKNOWN_SERIAL = "PROD-FAKE-GHOST-999"
    qr_unreg_pil, _ = create_anti_counterfeit_qr(
        f"https://brand-auth.com/verify?id={UNKNOWN_SERIAL}", UNKNOWN_SERIAL
    )
    img9 = cv2.cvtColor(np.array(qr_unreg_pil), cv2.COLOR_RGB2BGR)
    res9 = verify_anti_counterfeit_qr(img9)
    pinfo9 = res9.get("product_info", {})
    passed9 = (not pinfo9.get("is_registered", True)) or pinfo9.get("clone_alert", False)
    log_result(
        9, "Unknown / Unregistered Serial Number",
        "UNREGISTERED", "UNREGISTERED" if not pinfo9.get("is_registered") else "REGISTERED",
        res9.get("authenticity_score", 0), pinfo9.get("clone_message", "N/A"),
        res9.get("metrics"), passed9
    )

    # ──────────────────────────────────────────────────────────────────────────
    # Scenario 10: Genuine identifier with altered/substituted security graphic
    # ──────────────────────────────────────────────────────────────────────────
    # Embed CDP from another serial (B02) into TEST_SERIAL's QR
    _, cdp_other = create_anti_counterfeit_qr("https://fake.com", "PROD-DIFFERENT-SEED")
    cdp_other_cv = cv2.cvtColor(np.array(cdp_other), cv2.COLOR_RGB2BGR)
    tampered10 = qr_master_cv.copy()
    cw = int(w * 0.32)
    if cw % 2 != 0: cw += 1
    x1 = (w - cw) // 2
    y1 = (h - cw) // 2
    cdp_other_resized = cv2.resize(cdp_other_cv, (cw, cw))
    tampered10[y1:y1+cw, x1:x1+cw] = cdp_other_resized
    res10 = verify_anti_counterfeit_qr(tampered10, TEST_SERIAL)
    passed10 = (not res10.get("is_genuine")) and ("MISMATCH" in res10.get("verdict", "") or res10.get("authenticity_score", 0) <= 25.0)
    log_result(
        10, "Substituted Security Graphic (Wrong CDP)",
        "COUNTERFEIT", res10.get("status"), res10.get("authenticity_score", 0),
        res10.get("verdict"), res10.get("metrics"), passed10
    )

    # ──────────────────────────────────────────────────────────────────────────
    # Scenario 11: Unavailable reference or Revoked / Blacklisted product
    # ──────────────────────────────────────────────────────────────────────────
    BLACKLIST_SERIAL = "PROD-REVOKED-ITEM-88"
    product_db.register_product(
        serial_no=BLACKLIST_SERIAL,
        product_name="Recalled Heart Medication",
        brand_name="Aura Pharma Global",
        batch_no="B_REVOKED",
        mfg_date="2026-01-01",
        exp_date="2028-01-01",
        mrp="Rs. 900.00"
    )
    # Manually mark as REVOKED in DB
    conn = product_db.get_connection()
    conn.execute("UPDATE products SET status = 'REVOKED' WHERE serial_no = ?", (BLACKLIST_SERIAL,))
    conn.commit()
    conn.close()

    qr_revoked_pil, _ = create_anti_counterfeit_qr(
        f"https://brand-auth.com/verify?id={BLACKLIST_SERIAL}", BLACKLIST_SERIAL
    )
    img11 = cv2.cvtColor(np.array(qr_revoked_pil), cv2.COLOR_RGB2BGR)
    res11 = verify_anti_counterfeit_qr(img11, BLACKLIST_SERIAL)
    passed11 = (not res11.get("is_genuine")) and (res11.get("status") == "BLACKLISTED" or "REVOKED" in res11.get("verdict", ""))
    log_result(
        11, "Revoked / Blacklisted Serial Number",
        "BLACKLISTED", res11.get("status"), res11.get("authenticity_score", 0),
        res11.get("verdict"), res11.get("metrics"), passed11
    )

    # ──────────────────────────────────────────────────────────────────────────
    # Scenario 12: Repeated scans of the same identifier (Multi-scan clone alert)
    # ──────────────────────────────────────────────────────────────────────────
    # Scan same genuine code multiple times to trigger clone tracking
    MULTI_SERIAL = "PROD-MULTI-CLONE-55"
    product_db.register_product(
        serial_no=MULTI_SERIAL,
        product_name="Anti-Allergy Liquid 100ml",
        brand_name="Aura Pharma Global",
        batch_no="B55",
        mfg_date="2026-02-01",
        exp_date="2028-02-01",
        mrp="Rs. 320.00"
    )
    qr_multi_pil, _ = create_anti_counterfeit_qr(
        f"https://brand-auth.com/verify?id={MULTI_SERIAL}", MULTI_SERIAL
    )
    img12 = cv2.cvtColor(np.array(qr_multi_pil), cv2.COLOR_RGB2BGR)
    # 1st scan
    verify_anti_counterfeit_qr(img12, MULTI_SERIAL)
    # 2nd scan
    res12 = verify_anti_counterfeit_qr(img12, MULTI_SERIAL)
    pinfo12 = res12.get("product_info", {})
    passed12 = pinfo12.get("clone_alert") == True and pinfo12.get("scan_count", 0) >= 2
    log_result(
        12, "Repeated Scans / Multi-Scan Clone Alert",
        "CLONE_ALERT", "ALERT_TRIGGERED" if pinfo12.get("clone_alert") else "NO_ALERT",
        res12.get("authenticity_score", 0), pinfo12.get("clone_message"),
        res12.get("metrics"), passed12
    )

    # ──────────────────────────────────────────────────────────────────────────
    # Scenario 13: Stage 1 - Low Resolution Capture (< 200px)
    # ──────────────────────────────────────────────────────────────────────────
    img13 = cv2.resize(qr_master_cv, (160, 160))
    res13 = verify_anti_counterfeit_qr(img13, TEST_SERIAL)
    passed13 = res13.get("status") == "RECAPTURE_REQUIRED" and res13.get("authenticity_score") == 0.0
    log_result(
        13, "Stage 1 Quality: Low Resolution (< 200px)",
        "RECAPTURE_REQUIRED", res13.get("status"), res13.get("authenticity_score", 0),
        res13.get("verdict"), res13.get("metrics"), passed13
    )

    # ──────────────────────────────────────────────────────────────────────────
    # Scenario 14: Stage 1 - Specular Glare / Flash Reflection
    # ──────────────────────────────────────────────────────────────────────────
    glare14 = np.ones_like(qr_master_cv) * 255
    # Wash out 95% of pixels with glare
    img14 = cv2.addWeighted(qr_master_cv, 0.05, glare14, 0.95, 0)
    res14 = verify_anti_counterfeit_qr(img14, TEST_SERIAL)
    passed14 = res14.get("status") == "RECAPTURE_REQUIRED" and res14.get("authenticity_score") == 0.0
    log_result(
        14, "Stage 1 Quality: Specular Glare / Flash Reflection",
        "RECAPTURE_REQUIRED", res14.get("status"), res14.get("authenticity_score", 0),
        res14.get("verdict"), res14.get("metrics"), passed14
    )

    # ──────────────────────────────────────────────────────────────────────────
    # Scenario 15: Stage 1 - Damaged / Occluded Center Security Pattern
    # ──────────────────────────────────────────────────────────────────────────
    img15 = qr_master_cv.copy()
    cw15 = int(w * 0.32)
    x15 = (w - cw15) // 2
    y15 = (h - cw15) // 2
    # Place solid white sticker / smudge over central security pattern
    img15[y15:y15+cw15, x15:x15+cw15] = 255
    res15 = verify_anti_counterfeit_qr(img15, TEST_SERIAL)
    passed15 = res15.get("status") == "RECAPTURE_REQUIRED" and res15.get("authenticity_score") == 0.0
    log_result(
        15, "Stage 1 Quality: Occluded / Damaged Center CDP",
        "RECAPTURE_REQUIRED", res15.get("status"), res15.get("authenticity_score", 0),
        res15.get("verdict"), res15.get("metrics"), passed15
    )

    # ──────────────────────────────────────────────────────────────────────────
    # Final Metric Calculations
    # ──────────────────────────────────────────────────────────────────────────
    total_passed = sum(1 for r in results if r["passed"])
    print("=" * 78)
    print(f"SUMMARY: {total_passed} / {len(results)} SCENARIOS PASSED ({total_passed/len(results)*100:.1f}%)")
    print("=" * 78)

    # Performance metrics
    # Genuine cases: 1, 2, 3, 4, 5 (total 5)
    genuine_cases = [results[0], results[1], results[2], results[3], results[4]]
    genuine_accepted = sum(1 for r in genuine_cases if r["passed"])
    gar = (genuine_accepted / len(genuine_cases)) * 100.0
    frr = 100.0 - gar

    # Attack/Counterfeit cases: 8a (reprint), 8b (photocopier), 10 (tampered seed)
    attack_cases = [results[7], results[8], results[10]]
    counterfeits_caught = sum(1 for r in attack_cases if r["passed"])
    cdr = (counterfeits_caught / len(attack_cases)) * 100.0
    far = 100.0 - cdr

    # Unreadable cases: 7
    unreadable_caught = 1 if results[6]["passed"] else 0
    recapture_rate = (unreadable_caught / 1) * 100.0

    print(f"Genuine Acceptance Rate (GAR)  : {gar:.1f}%")
    print(f"False Rejection Rate (FRR)     : {frr:.1f}%")
    print(f"Counterfeit Detection Rate (CDR): {cdr:.1f}%")
    print(f"False Acceptance Rate (FAR)    : {far:.1f}%")
    print(f"Recapture / Unreadable Rate    : {recapture_rate:.1f}%")
    print("=" * 78)

    return total_passed == len(results)

if __name__ == "__main__":
    success = test_master_scenarios()
    sys.exit(0 if success else 1)
